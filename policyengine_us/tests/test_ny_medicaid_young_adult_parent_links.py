"""Generated grouping invariants for NY's parent-linked young-adult category.

NY DOH 13 OHIP/ADM-03 III.B.1(g) requires ages 19/20 and living with a parent.
Source-derived income/age examples and all 2017–2026 dollar boundaries live in
is_young_adult_for_medicaid.yaml. These six generated batches instead check
Core grouping behavior: scalar/vector agreement, member-order invariance,
resolving a parent outside the household, and MAGI monotonicity. They reuse
one read-only policy system and fresh calculation holders, without datasets
or reforms. This cannot be generated by the YAML test framework.
"""

from copy import deepcopy

import numpy as np
from hypothesis import given, settings, strategies as st
from policyengine_core.periods import period

from policyengine_us import Simulation
from policyengine_us.system import system


@st.composite
def parent_child_case(draw):
    return (
        draw(st.sampled_from(["NY", "CA", "DC"])),
        draw(st.sampled_from([18, 18.999, 19, 19.5, 20, 20.999, 21])),
        draw(st.booleans()),
        draw(st.integers(0, 4_000_000)) / 100,
        draw(st.integers(0, 1_000_000)) / 100,
    )


def situation(cases, year, reverse=False):
    result = {
        key: {}
        for key in ("people", "tax_units", "families", "marital_units", "households")
    }
    for index, (state, age, together, income, _) in enumerate(cases):
        parent, child = f"parent{index}", f"child{index}"
        parent_id = 2 * index + 101
        result["people"][parent] = {
            "person_id": {year: parent_id},
            "age": {year: 45},
            "employment_income": {year: income},
            "is_tax_unit_head": {year: True},
        }
        result["people"][child] = {
            "person_id": {year: parent_id + 1},
            "age": {year: age},
            "parent_1_id": {year: parent_id},
            "is_tax_unit_dependent": {year: True},
        }
        members = [parent, child]
        result["tax_units"][parent] = {"members": members}
        for name in members:
            result["marital_units"][name] = {"members": [name]}
        homes = [members] if together else [[parent], [child]]
        for home_index, home in enumerate(homes):
            name = f"home{index}_{home_index}"
            result["families"][name] = {"members": home}
            result["households"][name] = {"members": home, "state_code": {year: state}}
    if reverse:
        result["people"] = dict(reversed(list(result["people"].items())))
        for groups in result.values():
            for group in groups.values():
                if "members" in group:
                    group["members"] = list(reversed(group["members"]))
    return result


def evaluate(cases, year, reverse=False):
    inputs = situation(cases, year, reverse)
    sim = Simulation(tax_benefit_system=system, situation=inputs)
    names = list(inputs["people"])
    nfc = sim.calculate("is_young_adult_for_medicaid_nfc", year)
    eligible = sim.calculate("is_young_adult_for_medicaid", year)
    # The unchanged pre-2014 function is the actual legacy age-only NFC path.
    legacy = system.variables["is_young_adult_for_medicaid_nfc"].get_formula(2013)
    legacy_nfc = legacy(sim.persons, period(year), system.parameters)
    financial = sim.calculate("is_young_adult_for_medicaid_fc", year)
    for index, spec in enumerate(cases):
        if spec[0] != "NY":
            child = names.index(f"child{index}")
            assert nfc[child] == legacy_nfc[child]
            assert eligible[child] == (legacy_nfc[child] & financial[child])
    return {name: (bool(a), bool(b)) for name, a, b in zip(names, nfc, eligible)}


def test_ny_effective_date_preserves_pre_magi_sentinel():
    limits = system.parameters.gov.hhs.medicaid.eligibility.categories.young_adult.income_limit
    assert np.isneginf(limits.NY("2013-12-31"))
    assert limits.NY("2014-01-01") == 1.55


@settings(max_examples=6, deadline=None, derandomize=True)
@given(
    year=st.integers(2017, 2026),
    cases=st.lists(parent_child_case(), min_size=2, max_size=4),
)
def test_parent_links_are_stable_under_grouping_order_and_more_income(year, cases):
    # Include a co-resident and an absent-parent NY pair in every generated batch.
    cases = cases + [("NY", 19, True, 24_000, 2_000), ("NY", 20, False, 24_000, 2_000)]
    paired = []
    for state, age, together, income, increase in cases:
        paired.extend(
            [
                (state, age, together, income, 0),
                (state, age, together, income + increase, 0),
            ]
        )
    actual = evaluate(paired, year)
    assert evaluate(deepcopy(paired), year, reverse=True) == actual
    for index, spec in enumerate(paired):
        scalar = evaluate([spec], year)
        assert scalar["child0"] == actual[f"child{index}"]
        if spec[0] == "NY" and not spec[2]:
            assert actual[f"child{index}"] == (False, False)
    for index in range(0, len(paired), 2):
        assert actual[f"child{index}"][1] >= actual[f"child{index + 1}"][1]
